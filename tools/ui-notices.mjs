import {createRequire} from 'node:module';
import {readFile,writeFile} from 'node:fs/promises';
import {dirname,join} from 'node:path';
import {writeControlNotices} from './plugin-pack/notices.mjs';
const sdk = new URL('../packages/plugin-sdk/package.json',import.meta.url);
const requireFromSdk = createRequire(sdk), visited=new Set(), inputs={};
async function visit(name,requireFrom){
  const entry=requireFrom.resolve(name);let directory=dirname(entry),pkg;
  while(directory!==dirname(directory)){
    try{const value=JSON.parse(await readFile(join(directory,'package.json'),'utf8'));if(value.name===name){pkg=value;break;}}catch(error){if(error.code!=='ENOENT')throw error;}
    directory=dirname(directory);
  }
  if(!pkg)throw new Error(`Cannot locate package ${name}`);
  const id=`${pkg.name}@${pkg.version}`;if(visited.has(id))return;visited.add(id);inputs[entry]={};
  const child=createRequire(join(directory,'package.json'));
  for(const dependency of Object.keys(pkg.dependencies??{}))await visit(dependency,child);
}
const manifest=JSON.parse(await readFile(sdk,'utf8'));
for(const name of [...Object.keys(manifest.dependencies),'react','react-dom'])await visit(name,requireFromSdk);
const root=new URL('../packages/desktop-ui/',import.meta.url);
await writeControlNotices(root,inputs);
const notice=await readFile(new URL('THIRD_PARTY_NOTICES',root),'utf8');
await writeFile(new URL('src/ui-notices.ts',root),'// Generated by tools/ui-notices.mjs from public UI dependencies.\nexport const UI_NOTICES = '+JSON.stringify(notice.trim())+';\n');
console.log(`Public UI licenses: ${visited.size} packages`);
